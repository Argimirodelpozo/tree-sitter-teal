#!/usr/bin/env node
/**
 * Regenerate vocab/avm.json -- the AVM opcode and field vocabulary grammar.js
 * builds its rules from -- out of the official go-algorand language spec.
 *
 *   node scripts/gen_vocab.js                 # fetch the pinned langspec
 *   node scripts/gen_vocab.js langspec.json   # use a local copy
 *
 * The langspec is fetched at a PINNED commit and checked against a pinned
 * SHA-256, so the vocabulary is reproducible. To move to a newer AVM version,
 * bump SPEC below (commit, path, sha256), rerun this script, then
 * `tree-sitter generate && tree-sitter test && node scripts/check_spec.js`.
 *
 * Only facts are copied (opcode names, immediate shapes, field names, the
 * version each appeared in); no documentation text is redistributed.
 */
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const SPEC = {
  repository: "https://github.com/algorand/go-algorand",
  commit: "da5946a14568c0cbaa2c9daf4241882de12f3c16",
  path: "data/transactions/logic/langspec_v13.json",
  sha256: "2fb0d4c84a9bc5a93325dc18a61c521db8157a6aebcdf8b836c09f916d5e0cc2",
};

// The assembler's named integer constants for the `int` pseudo-op. They are
// NOT in the langspec; they come from the assembler itself, at the same commit:
//   data/transactions/logic/fields.go  TxnTypeNames, txnTypeLongNames,
//                                      OnCompletionConstType (NoOp..DeleteApplication)
//   protocol/txntype.go                 the short TxType names
// Long names containing a space ("State Proof", "Consensus heartbeat") can never
// be a single assembler token, so they are omitted.
const NAMED_INT_CONSTANTS = {
  unknown: 0, pay: 1, keyreg: 2, acfg: 3, axfer: 4, afrz: 5, appl: 6, stpf: 7, hb: 8,
  Payment: 1, KeyRegistration: 2, AssetConfig: 3, AssetTransfer: 4, AssetFreeze: 5,
  ApplicationCall: 6,
  NoOp: 0, OptIn: 1, CloseOut: 2, ClearState: 3, UpdateApplication: 4, DeleteApplication: 5,
};

// Assembler pseudo-ops (assembler.go `pseudoOps`) that are not opcodes of their own.
const PSEUDO_OPS = {
  int: "push an integer constant (number, named constant or template variable)",
  byte: "push a byte constant",
  addr: "push the 32-byte public key of an Algorand address",
  method: "push the 4-byte ARC-4 selector of a method signature",
  extract: "with NO immediates: assembles as extract3",
  replace: "with 0 immediates: replace3; with 1: replace2",
};

async function loadSpec(file) {
  let raw;
  if (file) {
    raw = fs.readFileSync(file);
  } else {
    const url = `https://raw.githubusercontent.com/algorand/go-algorand/${SPEC.commit}/${SPEC.path}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`GET ${url}: ${res.status}`);
    raw = Buffer.from(await res.arrayBuffer());
  }
  const digest = crypto.createHash("sha256").update(raw).digest("hex");
  if (digest !== SPEC.sha256) {
    throw new Error(`langspec sha256 ${digest} != pinned ${SPEC.sha256}`);
  }
  return JSON.parse(raw.toString("utf8"));
}

async function main() {
  const spec = await loadSpec(process.argv[2]);
  const ops = {};
  for (const op of [...spec.Ops].sort((a, b) => a.Opcode - b.Opcode)) {
    ops[op.Name] = {
      opcode: op.Opcode,
      since: op.IntroducedVersion,
      immediates: (op.ImmediateNote || []).map((im) => ({
        name: im.Name,
        encoding: im.Encoding,
        ...(im.Reference ? { reference: im.Reference } : {}),
      })),
      ...(op.ArgEnum ? {
        fields: (op.ArgDetails || op.ArgEnum.map((n) => ({ Name: n }))).map((d) => ({
          name: d.Name,
          since: d.Version || op.IntroducedVersion,
        })),
      } : {}),
    };
  }
  // A few ops (itxnas, gitxnas) carry no ArgEnum of their own in the langspec;
  // their field immediate REFERENCES a group another op spells out in full.
  const byReference = {};
  for (const op of spec.Ops) {
    const ref = (op.ImmediateNote || []).find((im) => im.Reference);
    if (ref && op.ArgEnum && !byReference[ref.Reference]) byReference[ref.Reference] = ops[op.Name].fields;
  }
  for (const [name, op] of Object.entries(ops)) {
    const ref = op.immediates.find((im) => im.reference);
    if (ref && !op.fields) {
      if (!byReference[ref.reference]) throw new Error(`${name}: no field list for ${ref.reference}`);
      op.fields = byReference[ref.reference];
    }
  }
  const out = {
    "//": "GENERATED by scripts/gen_vocab.js from the go-algorand langspec -- do not edit by hand",
    spec: { ...SPEC, avm_version: spec.Version },
    ops,
    pseudo_ops: PSEUDO_OPS,
    named_int_constants: NAMED_INT_CONSTANTS,
  };
  const dest = path.join(__dirname, "..", "vocab", "avm.json");
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, JSON.stringify(out, null, 1) + "\n");
  console.log(`wrote ${dest}: ${Object.keys(ops).length} opcodes, AVM v${spec.Version}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
